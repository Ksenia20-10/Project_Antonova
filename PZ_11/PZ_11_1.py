# 1. В последовательности на n целых чисел умножить элементы до n-1 на элемент n.
# Вариант 4. Задание 1

# Исходная последовательность
A = [3, 5, 2, 8, 1, 4, 6]
print("Исходная последовательность:", A)

n = len(A)  # количество элементов

if n >= 1:
    last_element = A[n - 1]  # элемент n (последний)

    # Умножаем элементы до n-1 (первые n-1 элементов) на последний элемент
    # Используем списковое включение
    result = [A[i] * last_element for i in range(n - 1)]

    print("Последний элемент (n):", last_element)
    print("Результат (элементы до n-1, умноженные на элемент n):", result)
else:
    print("Последовательность пуста")

print()
