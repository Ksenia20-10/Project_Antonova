# Вариант 4
# Книжные магазины предлагают следующие коллекции книг.
# Магистр – Лермонтов, Достоевский, Пушкин, Тютчев
# ДомКниги – Толстой, Грибоедов, Чехов, Пушкин.
# БукМаркет – Пушкин, Достоевский, Маяковский.
# Галерея – Чехов, Тютчев, Пушкин. Определить в каких магазинах
# можно приобрести книги Маяковского

# Исходные данные: множества книг в каждом магазине
magistr = {"Лермонтов", "Достоевский", "Пушкин", "Тютчев"}
domknigi = {"Толстой", "Грибоедов", "Чехов", "Пушкин"}
bukmarket = {"Пушкин", "Достоевский", "Маяковский"}
galereya = {"Чехов", "Тютчев", "Пушкин"}

# Книга, которую ищем
book = "Маяковский"

print("=== Исходные данные ===")
print("Магистр:", magistr)
print("ДомКниги:", domknigi)
print("БукМаркет:", bukmarket)
print("Галерея:", galereya)
print()
print(f"Ищем книгу: {book}")
print()

# Определяем, в каких магазинах есть эта книга
shops_with_book = []

if book in magistr:
    shops_with_book.append("Магистр")
if book in domknigi:
    shops_with_book.append("ДомКниги")
if book in bukmarket:
    shops_with_book.append("БукМаркет")
if book in galereya:
    shops_with_book.append("Галерея")

# Вывод результата
print("=== Результат ===")
if shops_with_book:
    print(f"Книгу '{book}' можно приобрести в магазинах:", ", ".join(shops_with_book))
else:
    print(f"Книгу '{book}' нельзя приобрести ни в одном магазине.")