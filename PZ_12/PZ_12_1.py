#1. В квадратной матрице все элементы, не лежащие на главной диагонали увеличить в 2 раза.
# Вариант 4

# Исходная квадратная матрица
matrix = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9]
]

print("Исходная матрица:")
for row in matrix:
    print(row)

# Увеличиваем в 2 раза элементы, не лежащие на главной диагонали
# Главная диагональ: индексы i == j
size = len(matrix)  # размер квадратной матрицы

for i in range(size):
    for j in range(size):
        if i != j:  # элемент не на главной диагонали
            matrix[i][j] *= 2

print("\nМатрица после преобразования:")
for row in matrix:
    print(row)

print()
